// Hero and contact frames of the live world (dev server on 5173, ?gl=force), with the cursor near her.
import { chromium } from '/home/ashen/Documents/projects/blakraMain/node_modules/playwright-core/index.mjs'
const out = process.argv[2]
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=vulkan', '--enable-features=Vulkan', '--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', (e) => console.log('pageerror', e.message))
p.on('console', (m) => { if (m.type() === 'error' || /navigator|observatory/.test(m.text())) console.log('console', m.text()) })
await p.goto('http://localhost:5173/?gl=force&profile', { waitUntil: 'networkidle' })
await p.waitForTimeout(7000)
await p.mouse.move(400, 500)
await p.waitForTimeout(1500)
await p.screenshot({ path: `${out}/hero-1440.png` })
await p.mouse.move(1300, 200)
await p.waitForTimeout(1500)
await p.screenshot({ path: `${out}/hero-1440-look.png` })
const H = await p.evaluate(() => document.documentElement.scrollHeight - innerHeight)
await p.evaluate((y) => scrollTo(0, y), H)
await p.waitForTimeout(2500)
await p.mouse.move(700, 450)
await p.waitForTimeout(1500)
await p.screenshot({ path: `${out}/contact-1440.png` })
await p.waitForTimeout(2500)
await b.close()
console.log('shots ok')
